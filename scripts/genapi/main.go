// Command genapi writes internal/app/api_gen.go: for each per-tab service
// (ServerService, ConfigService, …) a Wails-bound wrapper whose methods take
// the tab's id first and forward to that tab's service. Run it with
// `go run ./scripts/genapi` after changing a service's exported methods;
// TestAPIGenUpToDate fails until you do.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// services maps a per-tab service to its wrapper and the Tab field.
var services = []struct{ Type, Wrapper, Field string }{
	{"ServerService", "ServerAPI", "Server"},
	{"ConfigService", "ConfigAPI", "Config"},
	{"IssueService", "IssueAPI", "Issue"},
	{"LogService", "LogAPI", "Log"},
	{"InboxService", "InboxAPI", "Inbox"},
}

// skip are lifecycle methods the Hub handles.
var skip = map[string]bool{"ServiceStartup": true, "ServiceShutdown": true}

func main() {
	dir := "internal/app"
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	out, err := Generate(dir)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "api_gen.go"), out, 0o644); err != nil {
		log.Fatal(err)
	}
}

type method struct {
	name    string
	params  []param
	results []string
	doc     string
}

type param struct{ name, typ string }

// Generate returns the content of api_gen.go for the package in dir.
func Generate(dir string) ([]byte, error) {
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	methods := map[string][]method{}
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") || strings.HasSuffix(f, "api_gen.go") {
			continue
		}
		file, err := parser.ParseFile(fset, f, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, d := range file.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || !fd.Name.IsExported() || skip[fd.Name.Name] {
				continue
			}
			star, ok := fd.Recv.List[0].Type.(*ast.StarExpr)
			if !ok {
				continue
			}
			recv := star.X.(*ast.Ident).Name
			m := method{name: fd.Name.Name}
			if fd.Doc != nil {
				m.doc = fd.Doc.Text()
			}
			for _, p := range fd.Type.Params.List {
				typ := expr(fset, p.Type)
				for _, n := range p.Names {
					m.params = append(m.params, param{n.Name, typ})
				}
			}
			if fd.Type.Results != nil {
				for _, r := range fd.Type.Results.List {
					n := max(1, len(r.Names))
					for range n {
						m.results = append(m.results, expr(fset, r.Type))
					}
				}
			}
			methods[recv] = append(methods[recv], m)
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by scripts/genapi; DO NOT EDIT.\n\npackage app\n\n")
	b.WriteString("import (\n\t\"github.com/touhidurabir/visor/internal/config\"\n\t\"github.com/touhidurabir/visor/internal/describe\"\n\t\"github.com/touhidurabir/visor/internal/supervisor\"\n\t\"github.com/touhidurabir/visor/internal/validate\"\n)\n\n")
	b.WriteString("var (\n\t_ config.Template\n\t_ describe.Program\n\t_ supervisor.ConfigDiff\n\t_ validate.Check\n)\n\n")
	for _, s := range services {
		ms := methods[s.Type]
		sort.Slice(ms, func(i, j int) bool { return ms[i].name < ms[j].name })
		fmt.Fprintf(&b, "// %s is %s for the tab the frontend names first.\ntype %s struct{ hub *Hub }\n\n", s.Wrapper, s.Type, s.Wrapper)
		fmt.Fprintf(&b, "// New%s returns the wrapper over hub's tabs.\nfunc New%s(hub *Hub) *%s { return &%s{hub: hub} }\n\n", s.Wrapper, s.Wrapper, s.Wrapper, s.Wrapper)
		for _, m := range ms {
			writeMethod(&b, s.Wrapper, s.Field, m)
		}
	}
	return format.Source(b.Bytes())
}

func writeMethod(b *bytes.Buffer, wrapper, field string, m method) {
	if m.doc != "" {
		for _, l := range strings.Split(strings.TrimRight(m.doc, "\n"), "\n") {
			fmt.Fprintf(b, "// %s\n", l)
		}
	}
	params := []string{"server string"}
	args := []string{}
	for _, p := range m.params {
		params = append(params, p.name+" "+p.typ)
		arg := p.name
		if strings.HasPrefix(p.typ, "...") {
			arg += "..."
		}
		args = append(args, arg)
	}
	// Every wrapper can fail (the tab may be closed), so every one returns error.
	results := append([]string(nil), m.results...)
	hasErr := len(results) > 0 && results[len(results)-1] == "error"
	if !hasErr {
		results = append(results, "error")
	}
	fmt.Fprintf(b, "func (a *%s) %s(%s) (%s) {\n", wrapper, m.name, strings.Join(params, ", "), strings.Join(results, ", "))
	fmt.Fprintf(b, "\tt, err := a.hub.Tab(server)\n\tif err != nil {\n\t\treturn ")
	var zeros []string
	for _, r := range results[:len(results)-1] {
		zeros = append(zeros, zero(r))
	}
	fmt.Fprintf(b, "%s\n\t}\n", strings.Join(append(zeros, "err"), ", "))
	call := fmt.Sprintf("t.%s.%s(%s)", field, m.name, strings.Join(args, ", "))
	switch {
	case hasErr:
		fmt.Fprintf(b, "\treturn %s\n", call)
	case len(m.results) == 0:
		fmt.Fprintf(b, "\t%s\n\treturn nil\n", call)
	default:
		fmt.Fprintf(b, "\treturn %s, nil\n", call)
	}
	b.WriteString("}\n\n")
}

func zero(typ string) string {
	switch {
	case typ == "string":
		return `""`
	case typ == "bool":
		return "false"
	case typ == "int" || typ == "int64" || typ == "float64":
		return "0"
	case strings.HasPrefix(typ, "[]") || strings.HasPrefix(typ, "map[") || strings.HasPrefix(typ, "*"):
		return "nil"
	}
	return typ + "{}"
}

func expr(fset *token.FileSet, e ast.Expr) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, fset, e)
	return b.String()
}
